"""Render the tokens as Swift constants for NestKit (`Generated/DesignTokens.swift`)."""

from pydantic import BaseModel

from nestd.design.colors import parse_color
from nestd.design.models import GlassStyle, ThemedColor, Tokens
from nestd.design.swift_names import member_name, type_name
from nestd.design.tree import (
    Bezier,
    FontStack,
    Group,
    Leaf,
    Measure,
    Unit,
    format_number,
    token_tree,
)

HEADER = "// Generated by `nestd design generate` from design/tokens.toml. Do not edit.\n"

PRELUDE = """
import Foundation

/// Channels as fractions from 0 to 1.
public struct RGBA: Equatable, Sendable {
    public let red: Double
    public let green: Double
    public let blue: Double
    public let alpha: Double
}

public struct ThemedColor: Equatable, Sendable {
    public let light: RGBA
    public let dark: RGBA
}

public struct CubicBezier: Equatable, Sendable {
    public let x1: Double
    public let y1: Double
    public let x2: Double
    public let y2: Double
}

public struct AccentColor: Equatable, Sendable {
    public let name: String
    public let fill: ThemedColor
    /// Text and icons drawn on top of the fill.
    public let on: ThemedColor
}

/// A radial glow; positions and radii are fractions of the window size.
public struct WallpaperStop: Equatable, Sendable {
    public let color: ThemedColor
    public let centerX: Double
    public let centerY: Double
    public let radiusX: Double
    public let radiusY: Double
    /// Fraction of the radius where the glow has faded to transparent.
    public let fade: Double
}

public struct WallpaperStyle: Equatable, Sendable {
    public let name: String
    public let base: ThemedColor
    public let stops: [WallpaperStop]
}

/// What shows through the glass: blur radius in points, saturation as a factor.
public struct GlassBackdrop: Equatable, Sendable {
    public let blur: Double
    public let saturation: Double
}

public struct GlassColors: Equatable, Sendable {
    /// Panel tint.
    public let tint: ThemedColor
    /// Strong surface: menus, popovers, inputs.
    public let surface: ThemedColor
    public let surfaceSubtle: ThemedColor
    /// Border of a glass element.
    public let stroke: ThemedColor
    /// Thin outer line that separates the glass from what is behind it.
    public let edge: ThemedColor
    /// Specular highlight along the top edge.
    public let highlight: ThemedColor
    /// Rim along the bottom edge.
    public let rim: ThemedColor
    public let shadowColor: ThemedColor
    /// Project tab strip.
    public let strip: ThemedColor
    /// Window shell behind the panels.
    public let shell: ThemedColor
}

public struct GlassRadius: Equatable, Sendable {
    public let window: Double
    public let panel: Double
    public let pane: Double
    public let card: Double
    public let item: Double
    public let control: Double
    public let small: Double
    public let tab: Double
}

public struct GlassSpacing: Equatable, Sendable {
    public let gap: Double
    public let rowPaddingY: Double
    public let transcriptPaddingTop: Double
    public let transcriptPaddingX: Double
    public let transcriptPaddingBottom: Double
    public let transcriptGap: Double
    public let stripHeight: Double
    public let toolbarHeight: Double
}

/// A drop shadow: vertical offset, blur and spread in points.
public struct GlassShadow: Equatable, Sendable {
    public let y: Double
    public let blur: Double
    public let spread: Double
}

public struct GlassShadows: Equatable, Sendable {
    public let panel: GlassShadow
    /// The window casts two layered shadows.
    public let windowFar: GlassShadow
    public let windowNear: GlassShadow
}

/// A glass theme with every value resolved; `name` is the theme's id.
public struct GlassStyle: Equatable, Sendable {
    public let name: String
    public let displayName: String
    public let summary: String
    public let backdrop: GlassBackdrop
    public let colors: GlassColors
    public let radius: GlassRadius
    public let spacing: GlassSpacing
    public let shadow: GlassShadows
}

/// Durations are in seconds, saturation is a factor, sizes are in points.
"""

ORDER = (
    "colors",
    "status",
    "accent",
    "glass",
    "glass_theme",
    "wallpaper",
    "radius",
    "spacing",
    "typography",
    "motion",
)
INDENT = "    "


def render_swift(tokens: Tokens) -> str:
    sections = {group.name: _group(group, 1) for group in token_tree(tokens)}
    sections["accent"] = _accents(tokens)
    sections["glass_theme"] = _glass_themes(tokens)
    sections["wallpaper"] = _wallpapers(tokens)
    body = [line for name in ORDER for line in sections[name]]
    return HEADER + PRELUDE + "public enum DesignTokens {\n" + "\n".join(body) + "\n}\n"


def _group(group: Group, depth: int) -> list[str]:
    pad = INDENT * depth
    lines = [f"{pad}public enum {type_name(group.name)} {{"]
    for child in group.children:
        if isinstance(child, Leaf):
            lines.append(pad + INDENT + _leaf(child))
        else:
            lines.extend(_group(child, depth + 1))
    lines.append(f"{pad}}}")
    return lines


def _leaf(leaf: Leaf) -> str:
    name = member_name(leaf.name)
    value = leaf.value
    if isinstance(value, ThemedColor):
        return f"public static let {name} = {_themed(value)}"
    if isinstance(value, Measure):
        return f"public static let {name}: Double = {format_number(_native(value))}"
    if isinstance(value, FontStack):
        families = ", ".join(f'"{family}"' for family in value.families)
        return f"public static let {name}: [String] = [{families}]"
    return f"public static let {name} = {_bezier(value)}"


def _native(measure: Measure) -> float:
    if measure.unit is Unit.MILLISECONDS:
        return measure.value / 1000
    if measure.unit is Unit.PERCENT:
        return measure.value / 100
    return measure.value


def _rgba(text: str) -> str:
    color = parse_color(text)
    channels = (("red", color.red), ("green", color.green), ("blue", color.blue))
    parts = [f"{label}: {format_number(value)}" for label, value in channels]
    return f"RGBA({', '.join(parts)}, alpha: {format_number(color.alpha)})"


def _themed(color: ThemedColor) -> str:
    return f"ThemedColor(light: {_rgba(color.light)}, dark: {_rgba(color.dark)})"


def _bezier(curve: Bezier) -> str:
    points = (("x1", curve.x1), ("y1", curve.y1), ("x2", curve.x2), ("y2", curve.y2))
    return f"CubicBezier({', '.join(f'{k}: {format_number(v)}' for k, v in points)})"


def _choice(kind: str, struct: str, names: list[str], default: str, values: list[str]) -> list[str]:
    pad = INDENT * 2
    members = [member_name(name) for name in names]
    lines = [f"{INDENT}public enum {type_name(kind)} {{"]
    lines += [
        f"{pad}public static let {member} = {value}"
        for member, value in zip(members, values, strict=True)
    ]
    lines.append(f"{pad}public static let all: [{struct}] = [{', '.join(members)}]")
    lines.append(f"{pad}public static let `default` = {member_name(default)}")
    lines.append(f"{INDENT}}}")
    return lines


def _accents(tokens: Tokens) -> list[str]:
    options = tokens.accent.options
    values = [
        f'AccentColor(name: "{name}", fill: {_themed(accent.fill)}, on: {_themed(accent.on)})'
        for name, accent in options.items()
    ]
    return _choice("accent", "AccentColor", list(options), tokens.accent.default, values)


def _wallpapers(tokens: Tokens) -> list[str]:
    options = tokens.wallpaper.options
    pad = INDENT * 3
    values: list[str] = []
    for name, style in options.items():
        stops = [
            f"{pad}WallpaperStop(color: {_themed(stop.color)}, "
            f"centerX: {_fraction(stop.center[0])}, centerY: {_fraction(stop.center[1])}, "
            f"radiusX: {_fraction(stop.size[0])}, radiusY: {_fraction(stop.size[1])}, "
            f"fade: {_fraction(stop.fade)}),"
            for stop in style.stops
        ]
        head = f'WallpaperStyle(name: "{name}", base: {_themed(style.base)}, stops: ['
        values.append("\n".join([head, *stops, f"{INDENT * 2}])"]))
    return _choice("wallpaper", "WallpaperStyle", list(options), tokens.wallpaper.default, values)


def _fraction(percent: float) -> str:
    return format_number(percent / 100)


def _glass_themes(tokens: Tokens) -> list[str]:
    themes = tokens.glass.themes
    values = [_glass_style(name, style) for name, style in themes.options.items()]
    return _choice("glass_theme", "GlassStyle", list(themes.options), themes.default, values)


def _glass_style(name: str, style: GlassStyle) -> str:
    pad = INDENT * 3
    backdrop = style.backdrop
    colors = [f"{pad}{INDENT}{member_name(key)}: {_themed(color)}" for key, color in style.colors]
    shadows = ", ".join(f"{member_name(key)}: {_numbers(shadow)}" for key, shadow in style.shadow)
    return "\n".join(
        [
            "GlassStyle(",
            f'{pad}name: "{name}", displayName: "{style.name}", summary: "{style.description}",',
            f"{pad}backdrop: GlassBackdrop(blur: {format_number(backdrop.blur)}, "
            f"saturation: {_fraction(backdrop.saturation)}),",
            f"{pad}colors: GlassColors(",
            ",\n".join(colors),
            f"{pad}),",
            f"{pad}radius: {_numbers(style.radius)},",
            f"{pad}spacing: {_numbers(style.spacing)},",
            f"{pad}shadow: GlassShadows({shadows})",
            f"{INDENT * 2})",
        ]
    )


def _numbers(model: BaseModel) -> str:
    """A struct of numbers named like its model, with its fields in order."""
    fields = ", ".join(f"{member_name(key)}: {format_number(value)}" for key, value in model)
    return f"{type(model).__name__}({fields})"
