"""Render the tokens as CSS custom properties for the PWA (`web/src/generated/tokens.css`)."""

from collections.abc import Iterator, Sequence

from harness.design.errors import DesignError
from harness.design.models import ThemedColor, Tokens
from harness.design.tree import (
    Bezier,
    FontStack,
    Leaf,
    Measure,
    Node,
    Value,
    format_number,
    token_tree,
)

HEADER = "/* Generated by `harness design generate` from design/tokens.toml. Do not edit. */\n"
DARK_MEDIA = "@media (prefers-color-scheme: dark)"

type Themed = tuple[str, str, str]  # variable, light value, dark value
type Fixed = tuple[str, str]  # variable, value


def render_css(tokens: Tokens) -> str:
    themed, fixed = _variables(tokens)
    accents = list(_accent_overrides(tokens))
    _ensure_unique([name for name, *_ in themed] + [name for name, _ in fixed] + _ACCENT_SLOTS)
    light = [f"{name}: {value}" for name, value, _ in themed]
    light += [f"{name}: {value}" for name, value in fixed]
    dark = [f"{name}: {value}" for name, _, value in themed]
    rules = [
        _rule(":root", [*light, "color-scheme: light"]),
        f"{DARK_MEDIA} {{\n"
        + _rule(':root:not([data-theme="light"])', [*dark, "color-scheme: dark"], "  ")
        + "}\n",
        _rule(':root[data-theme="dark"]', [*dark, "color-scheme: dark"]),
        *accents,
        *_wallpaper_classes(tokens),
    ]
    return HEADER + "\n" + "\n".join(rules)


def _variable(path: Sequence[str]) -> str:
    return "--" + "-".join(path).replace("_", "-")


def _leaves(
    nodes: Sequence[Node], prefix: tuple[str, ...]
) -> Iterator[tuple[tuple[str, ...], Value]]:
    for node in nodes:
        path = (*prefix, node.name)
        if isinstance(node, Leaf):
            yield path, node.value
        else:
            yield from _leaves(node.children, path)


def _variables(tokens: Tokens) -> tuple[list[Themed], list[Fixed]]:
    themed: list[Themed] = []
    fixed: list[Fixed] = []
    for section in token_tree(tokens):
        # Neutral colors read best without a prefix: --text-primary, --surface-code.
        prefix = () if section.name == "colors" else (section.name,)
        for path, value in _leaves(section.children, prefix):
            if isinstance(value, ThemedColor):
                themed.append((_variable(path), value.light, value.dark))
            else:
                fixed.append((_variable(path), _value(value)))
    default = tokens.accent.options[tokens.accent.default]
    for part, color in (("fill", default.fill), ("on", default.on)):
        light = f"var(--accent-light-{part}, {color.light})"
        themed.append((f"--accent-{part}", light, f"var(--accent-dark-{part}, {color.dark})"))
    for name, style in tokens.wallpaper.options.items():
        themed.append((_variable(("wallpaper", name, "base")), style.base.light, style.base.dark))
        for index, stop in enumerate(style.stops, start=1):
            variable = _variable(("wallpaper", name, "stop", str(index)))
            themed.append((variable, stop.color.light, stop.color.dark))
    return themed, fixed


def _value(value: Measure | FontStack | Bezier) -> str:
    if isinstance(value, Measure):
        return format_number(value.value) + value.unit.value
    if isinstance(value, FontStack):
        return ", ".join(f'"{family}"' if " " in family else family for family in value.families)
    points = (value.x1, value.y1, value.x2, value.y2)
    return f"cubic-bezier({', '.join(format_number(point) for point in points)})"


# Set by a [data-accent] rule and read, with the default accent as fallback, on :root.
_ACCENT_SLOTS = [
    f"--accent-{theme}-{part}" for part in ("fill", "on") for theme in ("light", "dark")
]


def _accent_overrides(tokens: Tokens) -> Iterator[str]:
    for name, accent in tokens.accent.options.items():
        if name == tokens.accent.default:
            continue
        declarations = [
            f"--accent-{theme}-{part}: {value}"
            for part, color in (("fill", accent.fill), ("on", accent.on))
            for theme, value in (("light", color.light), ("dark", color.dark))
        ]
        yield _rule(f':root[data-accent="{name}"]', declarations)


def _wallpaper_classes(tokens: Tokens) -> Iterator[str]:
    for name, style in tokens.wallpaper.options.items():
        layers = [
            f"radial-gradient({_percent(stop.size)} at {_percent(stop.center)}, "
            f"var({_variable(('wallpaper', name, 'stop', str(index)))}), "
            f"transparent {format_number(stop.fade)}%)"
            for index, stop in enumerate(style.stops, start=1)
        ]
        layers.append(f"var({_variable(('wallpaper', name, 'base'))})")
        body = ",\n".join(f"    {layer}" for layer in layers)
        yield f".{_variable(('wallpaper', name))[2:]} {{\n  background:\n{body};\n}}\n"


def _percent(pair: tuple[float, float]) -> str:
    return " ".join(f"{format_number(value)}%" for value in pair)


def _rule(selector: str, declarations: Sequence[str], indent: str = "") -> str:
    body = "".join(f"{indent}  {declaration};\n" for declaration in declarations)
    return f"{indent}{selector} {{\n{body}{indent}}}\n"


def _ensure_unique(names: Sequence[str]) -> None:
    seen: set[str] = set()
    for name in names:
        if name in seen:
            msg = f"CSS variable {name} is defined twice; rename one of the tokens"
            raise DesignError(msg)
        seen.add(name)
