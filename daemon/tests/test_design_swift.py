import re
from pathlib import Path

import pytest

from nestd.design.loader import load_tokens
from nestd.design.swift import render_swift
from tests.design_support import REPO_ROOT, minimal_tokens, write_tokens

PRIMARY = (
    "public static let primary = ThemedColor("
    "light: RGBA(red: 0.101961, green: 0.105882, blue: 0.12549, alpha: 1), "
    "dark: RGBA(red: 0.94902, green: 0.952941, blue: 0.968627, alpha: 1))"
)


@pytest.fixture
def swift(tmp_path: Path) -> str:
    return render_swift(load_tokens(write_tokens(tmp_path, minimal_tokens())))


def _lines(swift: str) -> list[str]:
    return [line.strip() for line in swift.splitlines()]


def test_the_file_has_a_header_and_needs_only_foundation(swift: str) -> None:
    assert swift.startswith("// Generated by `nestd design generate` from design/tokens.toml.")
    assert "import Foundation\n" in swift
    assert "SwiftUI" not in swift
    assert "CGFloat" not in swift
    assert swift.count("{") == swift.count("}")


def test_value_types_are_public_sendable_structs(swift: str) -> None:
    for name in ("RGBA", "ThemedColor", "CubicBezier", "AccentColor", "WallpaperStop"):
        assert f"public struct {name}: Equatable, Sendable {{" in swift
    for name in (
        "WallpaperStyle",
        "GlassBackdrop",
        "GlassColors",
        "GlassRadius",
        "GlassSpacing",
        "GlassShadow",
        "GlassShadows",
        "GlassStyle",
    ):
        assert f"public struct {name}: Equatable, Sendable {{" in swift
    assert "    public let light: RGBA\n    public let dark: RGBA\n" in swift


def test_sections_are_nested_enums_in_a_fixed_order(swift: str) -> None:
    sections = re.findall(r"^    public enum (\w+) \{", swift, flags=re.MULTILINE)
    assert sections == [
        "Colors",
        "Status",
        "Accent",
        "Glass",
        "GlassTheme",
        "Wallpaper",
        "Radius",
        "Spacing",
        "Typography",
        "Motion",
    ]
    assert "public enum DesignTokens {" in swift
    assert "        public enum Text {\n            " + PRIMARY + "\n" in swift
    assert "        public enum Running {" in swift
    assert "        public enum LineHeight {" in swift


def test_colors_become_unit_rgba_pairs(swift: str) -> None:
    lines = _lines(swift)
    assert PRIMARY in lines
    assert (
        "public static let secondary = ThemedColor("
        "light: RGBA(red: 0.101961, green: 0.105882, blue: 0.12549, alpha: 0.68), "
        "dark: RGBA(red: 0.94902, green: 0.952941, blue: 0.968627, alpha: 0.7))"
    ) in lines


def test_numbers_are_doubles_in_native_units(swift: str) -> None:
    lines = _lines(swift)
    for line in (
        "public static let window: Double = 24",
        "public static let chip: Double = 7.5",
        "public static let md: Double = 8",
        "public static let normal: Double = 20",
        "public static let saturation: Double = 1.85",
        "public static let body: Double = 13",
        "public static let bold: Double = 700",
        "public static let fast: Double = 0.2",
    ):
        assert line in lines


def test_font_stacks_and_easings(swift: str) -> None:
    lines = _lines(swift)
    assert 'public static let system: [String] = ["-apple-system", "SF Pro Text"]' in lines
    assert "public static let pop = CubicBezier(x1: 0.2, y1: 0.9, x2: 0.3, y2: 1.15)" in lines


def test_accents_list_every_option_and_name_the_default(swift: str) -> None:
    lines = _lines(swift)
    assert any(
        line.startswith('public static let ocean = AccentColor(name: "ocean", ') for line in lines
    )
    assert "public static let all: [AccentColor] = [graphite, ocean]" in lines
    assert "public static let `default` = graphite" in lines


def test_wallpapers_carry_their_stops_as_fractions(swift: str) -> None:
    lines = _lines(swift)
    assert (
        'public static let stone = WallpaperStyle(name: "stone", base: ThemedColor('
        in "\n".join(lines)
    )
    assert "centerX: 0.12, centerY: 0.18, radiusX: 0.55, radiusY: 0.65, fade: 0.7)" in swift
    assert "public static let all: [WallpaperStyle] = [stone]" in lines
    assert "public static let `default` = stone" in lines


def test_swift_keywords_are_escaped(tmp_path: Path) -> None:
    data = minimal_tokens()
    data["radius"]["default"] = 4
    data["colors"]["protocol"] = {"in": {"light": "#000000", "dark": "#ffffff"}}
    swift = render_swift(load_tokens(write_tokens(tmp_path, data)))
    assert "public static let `default`: Double = 4" in swift
    assert "public enum `Protocol` {" in swift
    assert "public static let `in` = ThemedColor(" in swift


def test_repository_swift_is_deterministic_and_balanced() -> None:
    tokens = load_tokens(REPO_ROOT / "design" / "tokens.toml")
    swift = render_swift(tokens)
    assert swift == render_swift(tokens)
    assert swift.count("{") == swift.count("}")
    assert swift.count("(") == swift.count(")")
    assert "public static let headline: Double = 17" in swift
    assert (
        "public static let all: [AccentColor] = [graphite, ocean, teal, moss, clay, rose]" in swift
    )
    assert "public static let all: [GlassStyle] = [clear, frosted, smoke, bluegrey, deep]" in swift
    assert 'name: "bluegrey", displayName: "Blue Grey",' in swift


def _theme(swift: str, name: str) -> str:
    start = swift.index(f"public static let {name} = GlassStyle(")
    return swift[start : swift.index("\n        )\n", start)]


def test_glass_themes_are_full_styles_with_a_default(swift: str) -> None:
    lines = _lines(swift)
    assert "public static let all: [GlassStyle] = [clear, deep]" in lines
    assert "public static let `default` = clear" in lines
    clear = _theme(swift, "clear")
    assert 'name: "clear", displayName: "Clear", summary: "The base layer.",' in clear
    assert "backdrop: GlassBackdrop(blur: 10, saturation: 1.6)," in clear
    assert (
        "radius: GlassRadius(window: 24, panel: 20, pane: 18, card: 14, item: 10, "
        "control: 999, small: 7, tab: 12)," in clear
    )
    assert (
        "spacing: GlassSpacing(gap: 10, rowPaddingY: 7, transcriptPaddingTop: 14, "
        "transcriptPaddingX: 16, transcriptPaddingBottom: 10, transcriptGap: 11, "
        "stripHeight: 46, toolbarHeight: 48)," in clear
    )
    assert (
        "shadow: GlassShadows(panel: GlassShadow(y: 10, blur: 28, spread: -16), "
        "windowFar: GlassShadow(y: 50, blur: 100, spread: -40), "
        "windowNear: GlassShadow(y: 18, blur: 36, spread: -18))" in clear
    )
    assert "colors: GlassColors(\n                tint: ThemedColor(light: RGBA(red: 1," in clear
    assert "\n                shadowColor: ThemedColor(" in clear
    assert "surfaceSubtle: ThemedColor(" in clear


def test_a_glass_theme_carries_its_inherited_values(swift: str) -> None:
    deep = _theme(swift, "deep")
    assert "backdrop: GlassBackdrop(blur: 44, saturation: 1.6)," in deep
    assert "radius: GlassRadius(window: 28, panel: 20," in deep
    assert "shadow: GlassShadows(panel: GlassShadow(y: 22, blur: 50, spread: -20), " in deep
    assert "tint: ThemedColor(light: RGBA(red: 0.627451, green: 0.682353," in deep


def test_the_glass_style_fields_follow_the_initializer_order(swift: str) -> None:
    style = swift[swift.index("public struct GlassStyle") :]
    style = style[: style.index("}")]
    fields = re.findall(r"public let (\w+):", style)
    assert fields == [
        "name",
        "displayName",
        "summary",
        "backdrop",
        "colors",
        "radius",
        "spacing",
        "shadow",
    ]
    spacing = swift[swift.index("public struct GlassSpacing") :]
    assert re.findall(r"public let (\w+):", spacing[: spacing.index("}")]) == [
        "gap",
        "rowPaddingY",
        "transcriptPaddingTop",
        "transcriptPaddingX",
        "transcriptPaddingBottom",
        "transcriptGap",
        "stripHeight",
        "toolbarHeight",
    ]
