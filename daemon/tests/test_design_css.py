import re
from pathlib import Path

import pytest

from harness.design.css import render_css
from harness.design.errors import DesignError
from harness.design.loader import load_tokens
from harness.design.models import Tokens
from tests.design_support import REPO_ROOT, minimal_tokens, write_tokens

DARK_MEDIA = '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n'
DARK_EXPLICIT = ':root[data-theme="dark"] {\n'


@pytest.fixture
def css(tmp_path: Path) -> str:
    return render_css(load_tokens(write_tokens(tmp_path, minimal_tokens())))


def _block(css: str, opener: str, indent: str = "") -> str:
    start = css.index(opener) + len(opener)
    return css[start : css.index(f"{indent}}}\n", start)]


def _declarations(block: str) -> dict[str, str]:
    return dict(re.findall(r"^\s*(--[a-z0-9-]+): (.+);$", block, flags=re.MULTILINE))


def test_the_file_starts_with_a_generated_header(css: str) -> None:
    assert css.startswith("/* Generated by `harness design generate` from design/tokens.toml.")
    assert css.endswith("}\n")


def test_light_values_live_on_root_and_dark_values_in_both_dark_blocks(css: str) -> None:
    light = _declarations(_block(css, ":root {\n"))
    media = _block(css, DARK_MEDIA, "  ")
    explicit = _block(css, DARK_EXPLICIT)
    assert light["--text-primary"] == "#1a1b20"
    assert light["--text-secondary"] == "rgba(26,27,32,0.68)"
    assert _declarations(media)["--text-primary"] == "#f2f3f7"
    assert _declarations(media) == _declarations(explicit)
    assert "color-scheme: light;" in _block(css, ":root {\n")
    assert "    color-scheme: dark;" in media
    assert "  color-scheme: dark;" in explicit


def test_status_glass_and_wallpaper_colors_are_themed(css: str) -> None:
    dark = _declarations(_block(css, DARK_EXPLICIT))
    for name in (
        "--status-running-fill",
        "--status-interrupted-soft",
        "--glass-tint-regular",
        "--glass-specular",
        "--wallpaper-stone-base",
        "--wallpaper-stone-stop-2",
    ):
        assert name in dark
    assert dark["--wallpaper-stone-stop-1"] == "#3b342a"


def test_the_default_accent_is_the_fallback_of_the_accent_variables(css: str) -> None:
    light = _declarations(_block(css, ":root {\n"))
    dark = _declarations(_block(css, DARK_EXPLICIT))
    assert light["--accent-fill"] == "var(--accent-light-fill, #2b2b2e)"
    assert light["--accent-on"] == "var(--accent-light-on, #ffffff)"
    assert dark["--accent-fill"] == "var(--accent-dark-fill, #e6e6e9)"
    assert dark["--accent-on"] == "var(--accent-dark-on, #141416)"


def test_other_accents_override_the_fallbacks(css: str) -> None:
    ocean = _declarations(_block(css, ':root[data-accent="ocean"] {\n'))
    assert ocean == {
        "--accent-light-fill": "#2c6a9a",
        "--accent-dark-fill": "#79b4e3",
        "--accent-light-on": "#ffffff",
        "--accent-dark-on": "#141416",
    }
    assert 'data-accent="graphite"' not in css


def test_wallpapers_become_classes_layering_glows_over_the_base(css: str) -> None:
    assert _block(css, ".wallpaper-stone {\n") == (
        "  background:\n"
        "    radial-gradient(55% 65% at 12% 18%, var(--wallpaper-stone-stop-1), transparent 70%),\n"
        "    radial-gradient(50% 60% at 88% 10%, var(--wallpaper-stone-stop-2), transparent 72%),\n"
        "    var(--wallpaper-stone-base);\n"
    )


def test_scales_carry_their_css_units(css: str) -> None:
    light = _declarations(_block(css, ":root {\n"))
    assert light["--radius-window"] == "24px"
    assert light["--radius-chip"] == "7.5px"
    assert light["--spacing-md"] == "8px"
    assert light["--glass-blur-normal"] == "20px"
    assert light["--glass-saturation"] == "185%"
    assert light["--typography-size-body"] == "13px"
    assert light["--typography-weight-bold"] == "700"
    assert light["--typography-line-height-body"] == "1.4"
    assert light["--typography-family-system"] == '-apple-system, "SF Pro Text"'
    assert light["--motion-duration-fast"] == "200ms"
    assert light["--motion-easing-pop"] == "cubic-bezier(0.2, 0.9, 0.3, 1.15)"


def test_scales_are_not_repeated_in_the_dark_blocks(css: str) -> None:
    assert "--radius-window" not in _block(css, DARK_EXPLICIT)


def test_variable_names_must_be_unique(tmp_path: Path) -> None:
    data = minimal_tokens()
    data["colors"]["status"] = {"running_fill": {"light": "#000000", "dark": "#ffffff"}}
    tokens = load_tokens(write_tokens(tmp_path, data))
    with pytest.raises(DesignError, match="--status-running-fill is defined twice"):
        render_css(tokens)


def _repository_tokens() -> Tokens:
    return load_tokens(REPO_ROOT / "design" / "tokens.toml")


def test_repository_css_is_well_formed_and_complete_in_both_themes() -> None:
    css = render_css(_repository_tokens())
    assert css == render_css(_repository_tokens())
    assert css.count("{") == css.count("}")
    light = _declarations(_block(css, ":root {\n"))
    media = _declarations(_block(css, DARK_MEDIA, "  "))
    explicit = _declarations(_block(css, DARK_EXPLICIT))
    assert media == explicit
    themed = {name for name, value in light.items() if re.match(r"#|rgba|var\(--accent", value)}
    assert themed == set(media)
    declared = set(re.findall(r"(--[a-z0-9-]+):", css))
    used = set(re.findall(r"var\((--[a-z0-9-]+)", css))
    assert used <= declared
    accents = re.findall(r':root\[data-accent="([a-z]+)"\]', css)
    assert accents == ["ocean", "teal", "moss", "clay", "rose"]
    assert re.findall(r"^\.wallpaper-([a-z]+) \{", css, flags=re.MULTILINE) == [
        "stone",
        "sage",
        "sky",
        "slate",
    ]
